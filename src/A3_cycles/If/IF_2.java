package A3_cycles.If;

public class IF_2 {
    public static void main(String[] args) {
        int i = 0;
        int j = 1;
        int a = (j += (j < 1) ? (+j) : (++i));
        System.out.println(a);
    }

    /*
    1. Условный оператор (тернарный оператор):
            - Здесь мы смотрим на условие: j < 1. В этом примере j = 1, следовательно, условие ложно.
   - Раз условие ложно, мы переходим ко второй части тернарного выражения: ++i.

     2. Инкремент i:
     - ++i увеличивает значение i на 1, таким образом: i становится равным 1 (так как изначально было 0).
     - Однако ++i возвращает новое значение i, то есть 1.

     3. Присвоение j:
     - Теперь выражение j += ... становится: j += 1.
     - Так как j изначально равен 1, то:
     - j = j + 1 → j станет равным 2.

     4. Присвоение a:
     - Теперь a будут присвоен результат последнего выражения: a = j, что в данном случае будет 2.

     Шаг 3: Вывод результата

     Наконец, мы выводим значение a с помощью System.out.println(a):
     - Таким образом, на экране будет напечатано: 2.

      ### Полный вывод о выполнении программы

      По сумме всех шагов, программа выполнится следующим образом:
      - i станет равным 1.
      - j станет равным 2.
      - Значение a, равное 2, будет напечатано.
     */
}
